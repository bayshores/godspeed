/// The generic name of a zone, or None when Intl has none.
pub fn generic_name(zone: &str) -> Option<&'static str> {
	ZONES.binary_search_by_key(&zone, |(name, _)| name).ok().map(|at| LABELS[usize::from(ZONES[at].1)])
}

